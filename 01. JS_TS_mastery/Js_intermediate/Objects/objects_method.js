// Object.keys() - Give me all the name tags
console.log("Objects.keys:");
const user = {name: "Shahruk", age: 26, city: "Dhaka"};
console.log(Object.keys(user));
console.log();

// Object.values() - Give me all the actuall stuff
console.log("Object.values:");
console.log(Object.values(user));
console.log();

// Objects.entries() - Give me key value pairs
console.log("Object.entries:");
console.log(Object.entries(user));
console.log();







